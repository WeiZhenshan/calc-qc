INSERT INTO shared_brand (id, name, wholesale, sort_order)
SELECT UUID(), name, price, pos - 1 FROM JSON_TABLE(@seed, '$[*]' COLUMNS(
    pos FOR ORDINALITY, name VARCHAR(120) PATH '$[0]', price DECIMAL(15,6) PATH '$[1]'
)) s WHERE @catalog_source IS NULL;
INSERT INTO shared_tag (name, sort_order)
SELECT maker, MIN(pos) FROM JSON_TABLE(@seed, '$[*]' COLUMNS(
    pos FOR ORDINALITY, NESTED PATH '$[2][*]' COLUMNS(maker VARCHAR(12) PATH '$')
)) s WHERE @catalog_source IS NULL AND maker IS NOT NULL GROUP BY maker;
INSERT INTO shared_brand_tag (brand_id, tag_name, sort_order)
SELECT b.id, s.maker, s.tag_pos FROM JSON_TABLE(@seed, '$[*]' COLUMNS(
    name VARCHAR(120) PATH '$[0]', NESTED PATH '$[2][*]' COLUMNS(tag_pos FOR ORDINALITY, maker VARCHAR(12) PATH '$')
)) s JOIN shared_brand b ON b.name = s.name WHERE @catalog_source IS NULL AND s.maker IS NOT NULL;

-- Prefer the existing UUID, then an unambiguous name in the shared catalog.
-- Unmatched legacy records remain in the original private tables for recovery.
INSERT INTO user_calculation_item (user_id, brand_id, wholesale_override, market_override, quantity, is_hidden)
WITH unique_names AS (
    SELECT name, MIN(id) AS id FROM shared_brand GROUP BY name HAVING COUNT(*) = 1
), candidates AS (
    SELECT i.*, COALESCE(b.id, n.id) AS target_id,
        ROW_NUMBER() OVER (PARTITION BY i.user_id, COALESCE(b.id, n.id)
            ORDER BY (b.id IS NOT NULL) DESC, old.sort_order, old.id) AS priority,
        COUNT(*) OVER (PARTITION BY i.user_id, COALESCE(b.id, n.id)) AS matches_for_target
    FROM calc_snapshot_item i JOIN brand old ON old.user_id = i.user_id AND old.id = i.brand_id
    LEFT JOIN shared_brand b ON b.id = i.brand_id
    LEFT JOIN unique_names n ON n.name = old.name
)
SELECT user_id, target_id, wholesale_override, market_override, quantity, is_hidden
FROM candidates WHERE target_id IS NOT NULL AND priority = 1 AND (matches_for_target = 1 OR target_id = brand_id);
COMMIT;
